const root = path.resolve(import.meta.dirname, "..")
const require = createRequire(import.meta.url)
const set = JSON.parse(readFileSync(require.resolve("@iconify-json/ph/icons.json"), "utf8")) as {
  icons: Record<string, { body: string }>
}

/** Path data of one Phosphor icon; refuses anything but plain currentColor paths. */
function paths(name: string): string[] {
  const icon = set.icons[name]
  if (!icon) throw new Error(`Phosphor icon not found: ${name}`)
  const parts = icon.body.match(/<path[^>]*\/>/g) ?? []
  if (parts.join("") !== icon.body) throw new Error(`Unexpected markup in ${name}`)
  return parts.map((p) => {
    const m = /^<path fill="currentColor" d="([^"]+)"\/>$/.exec(p)
    if (!m) throw new Error(`Unexpected path attributes in ${name}`)
    return m[1]!
  })
}

const lines = Object.entries(ICONS).map(([exportName, spec]) => {
  const [name, extra] = typeof spec === "string" ? [spec, []] : spec
  const weights: Weight[] = ["light", ...extra]
  const data = weights
    .map((w) => `${w}: ${JSON.stringify(paths(w === "light" ? `${name}-light` : `${name}-${w}`))}`)
    .join(", ")
  return `export const ${exportName} = /* @__PURE__ */ icon("${name}", { ${data} })`
})
const aliases = Object.entries(ALIASES).map(([a, target]) => `export const ${a} = ${target}`)

const source = `// Generated by scripts/gen-ui-icons.ts from Phosphor Icons (MIT, phosphoricons.com).
// Do not edit by hand: change the list in the script and run \`pnpm icons:ui\`.
import type { SVGProps } from "react"

/** Light is the house style; bold for tiny marks, fill for active/selected states. */
export type IconWeight = "light" | "bold" | "fill"
export type IconProps = SVGProps<SVGSVGElement> & { weight?: IconWeight }
export type IconComponent = ((props: IconProps) => React.JSX.Element) & { displayName?: string }

function icon(name: string, data: { light: string[] } & Partial<Record<IconWeight, string[]>>) {
  function Icon({ weight = "light", className, ...props }: IconProps) {
    const d = data[weight] ?? data.light
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={24}
        height={24}
        viewBox="0 0 256 256"
        fill="currentColor"
        aria-hidden={props["aria-label"] || props["aria-labelledby"] ? undefined : true}
        data-icon={name}
        data-weight={weight}
        className={className ? \`icon \${className}\` : "icon"}
        {...props}
      >
        {d.map((p) => (
          <path key={p} d={p} />
        ))}
      </svg>
    )
  }
  Icon.displayName = name
  return Icon as IconComponent
}

${lines.join("\n")}

${aliases.join("\n")}
`

